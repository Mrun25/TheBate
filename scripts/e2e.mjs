import {createWalletClient,createPublicClient,http,defineChain,parseEther,formatEther} from 'viem';
import {privateKeyToAccount} from 'viem/accounts';
import fs from 'fs';
const chain=defineChain({id:10143,name:'Monad Testnet',nativeCurrency:{name:'MON',symbol:'MON',decimals:18},rpcUrls:{default:{http:['https://testnet-rpc.monad.xyz']}}});
const {abi}=JSON.parse(fs.readFileSync('artifacts/TheBate.json','utf8'));
const {address}=JSON.parse(fs.readFileSync('deployment.json','utf8'));
const account=privateKeyToAccount(fs.readFileSync('.deployer.key','utf8').trim());
const pub=createPublicClient({chain,transport:http()});
const w=createWalletClient({account,chain,transport:http()});
const send=async(fn,args,value)=>{const h=await w.writeContract({address,abi,functionName:fn,args,value,gas:250000n});const r=await pub.waitForTransactionReceipt({hash:h});if(r.status!=='success')throw new Error(fn+' reverted '+h);console.log(fn,h);await new Promise(r=>setTimeout(r,2500));return h};
await send('createDebate',['Is AGI already here?'],parseEther('0.1'));
await new Promise(r=>setTimeout(r,2500));const id=await pub.readContract({address,abi,functionName:'debateCount'});console.log('debate id',id);
await send('stake',[id,0],parseEther('0.01'));
await send('stake',[id,1],parseEther('0.02'));
await send('resolve',[id,1]);
await send('claim',[id]);
console.log(await pub.readContract({address,abi,functionName:'getDebate',args:[id]}));
